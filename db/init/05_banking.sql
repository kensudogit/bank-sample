-- ====================================================================
-- Deposits
-- ====================================================================
-- Balance is kept in the currency's minor unit (JPY: yen, USD/EUR: cents).
-- Checking accounts may go negative down to the overdraft limit (当座貸越).
ALTER TABLE account ADD (
  currency         VARCHAR2(3)   DEFAULT 'JPY' NOT NULL,
  overdraft_limit  NUMBER(15,0)  DEFAULT 0 NOT NULL
);
ALTER TABLE account DROP CONSTRAINT ck_account_type;
ALTER TABLE account ADD CONSTRAINT ck_account_type
  CHECK (account_type IN ('ORDINARY', 'SAVINGS', 'CHECKING', 'TIME', 'FOREIGN', 'NOTICE'));
ALTER TABLE account DROP CONSTRAINT ck_account_balance;
ALTER TABLE account ADD CONSTRAINT ck_account_balance CHECK (balance >= -overdraft_limit);
ALTER TABLE account ADD CONSTRAINT ck_account_currency CHECK (currency IN ('JPY', 'USD', 'EUR'));
ALTER TABLE account ADD CONSTRAINT ck_account_overdraft CHECK (overdraft_limit >= 0);

ALTER TABLE account_transaction DROP CONSTRAINT ck_tx_type;
ALTER TABLE account_transaction ADD CONSTRAINT ck_tx_type CHECK (tx_type IN (
  'DEPOSIT', 'WITHDRAWAL', 'TRANSFER_OUT', 'TRANSFER_IN', 'INTEREST', 'TAX', 'CLOSE_PAYOUT',
  'FX_OUT', 'FX_IN', 'LOAN_DISB', 'LOAN_REPAY', 'FEE', 'DIRECT_DEBIT', 'REMIT_OUT', 'REMIT_IN', 'OD_INTEREST'));

