CREATE TABLE loan (
  loan_id               NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
  application_id        NUMBER(19)         NOT NULL,
  customer_id           VARCHAR2(10)       NOT NULL,
  product               VARCHAR2(12)       NOT NULL,
  principal             NUMBER(15,0)       NOT NULL,
  outstanding           NUMBER(15,0)       NOT NULL,
  credit_limit          NUMBER(15,0),
  annual_rate           NUMBER(7,5)        NOT NULL,
  term_months           NUMBER(3)          NOT NULL,
  repayment_method      VARCHAR2(16)       NOT NULL,
  repayment_account_no  VARCHAR2(7)        NOT NULL,
  payment_day           NUMBER(2)          NOT NULL,
  grade                 VARCHAR2(1)        NOT NULL,
  contract_date         DATE               NOT NULL,
  start_date            DATE,
  maturity_date         DATE,
  accrued_interest      NUMBER(17,2)       DEFAULT 0 NOT NULL,
  last_accrual_date     DATE,
  status                VARCHAR2(12)       DEFAULT 'CONTRACTED' NOT NULL,
  borrower_class        VARCHAR2(10)       DEFAULT 'NORMAL' NOT NULL,
  days_past_due         NUMBER(5)          DEFAULT 0 NOT NULL,
  contracted_by         VARCHAR2(30),
  executed_by           VARCHAR2(30),
  executed_at           TIMESTAMP,
  closed_at             TIMESTAMP,
  CONSTRAINT pk_loan PRIMARY KEY (loan_id),
  CONSTRAINT fk_loan_application FOREIGN KEY (application_id) REFERENCES loan_application (application_id),
  CONSTRAINT fk_loan_customer FOREIGN KEY (customer_id) REFERENCES customer (customer_id),
  CONSTRAINT fk_loan_repay_account FOREIGN KEY (repayment_account_no) REFERENCES account (account_no),
  CONSTRAINT ck_loan_status CHECK (status IN ('CONTRACTED', 'ACTIVE', 'DELINQUENT', 'PAID_OFF', 'WRITTEN_OFF')),
  CONSTRAINT ck_loan_class CHECK (borrower_class IN ('NORMAL', 'WATCH', 'SPECIAL', 'DOUBTFUL', 'DEFACTO', 'BANKRUPT')),
  CONSTRAINT ck_loan_outstanding CHECK (outstanding >= 0)
