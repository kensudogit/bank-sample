INSERT INTO interest_rate (account_type, effective_from, annual_rate) VALUES ('SAVINGS', DATE '2025-01-01', 0.25);

-- ---- Interest settlements (one row per account and settled period) ----
CREATE TABLE interest_settlement (
  settlement_id   NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY,
  account_no      VARCHAR2(7)    NOT NULL,
  period_from     DATE           NOT NULL,
  period_to       DATE           NOT NULL,
  days            NUMBER(5)      NOT NULL,
  balance_days    NUMBER(22,0)   NOT NULL,
  gross_interest  NUMBER(15,0)   NOT NULL,
  national_tax    NUMBER(15,0)   NOT NULL,
  local_tax       NUMBER(15,0)   NOT NULL,
  net_interest    NUMBER(15,0)   NOT NULL,
  settled_at      TIMESTAMP      NOT NULL,
  CONSTRAINT pk_interest_settlement PRIMARY KEY (settlement_id),
  CONSTRAINT fk_settlement_account FOREIGN KEY (account_no) REFERENCES account (account_no),
  CONSTRAINT uq_settlement_period UNIQUE (account_no, period_to),
  CONSTRAINT ck_settlement_period CHECK (period_from <= period_to)
);

COMMENT ON TABLE interest_rate IS '預金金利（年利%、種別・適用開始日ごと）';
COMMENT ON TABLE interest_settlement IS '利息決算（期間・積数・税引前利息・源泉税）';

