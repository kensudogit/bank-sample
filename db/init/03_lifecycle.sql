-- For an existing database (created before this file existed) apply it once (DDL fails harmlessly if re-run):
--   docker compose exec oracle bash -c "sqlplus -s / as sysdba @/container-entrypoint-initdb.d/03_lifecycle.sql"
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = BANK;

-- ---- Customer: identity information and KYC (本人確認) ----
ALTER TABLE customer ADD (
  name_kana        VARCHAR2(100 CHAR),
  birth_date       DATE,
  postal_code      VARCHAR2(8),
  address          VARCHAR2(200 CHAR),
  phone            VARCHAR2(15),
  id_doc_type      VARCHAR2(20),
  id_doc_last4     VARCHAR2(4),
  kyc_status       VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
  kyc_decided_at   TIMESTAMP,
  kyc_note         VARCHAR2(200 CHAR)
);

ALTER TABLE customer ADD CONSTRAINT ck_customer_kyc CHECK (kyc_status IN ('PENDING', 'VERIFIED', 'REJECTED'));
ALTER TABLE customer ADD CONSTRAINT ck_customer_id_doc
  CHECK (id_doc_type IS NULL OR id_doc_type IN ('DRIVER_LICENSE', 'MY_NUMBER_CARD', 'PASSPORT', 'RESIDENCE_CARD'));
-- Name matching (名寄せ) for duplicate applications
CREATE INDEX ix_customer_kana_birth ON customer (name_kana, birth_date);

-- Existing (seed) customers were verified at the counter
UPDATE customer SET kyc_status = 'VERIFIED', kyc_decided_at = created_at, kyc_note = '窓口にて確認済（移行データ）'
  WHERE kyc_decided_at IS NULL AND customer_id IN ('CU0001', 'CU0002', 'CU0003');

CREATE SEQUENCE customer_seq START WITH 5 NOCACHE;

-- ---- Account: closure and dormancy ----
ALTER TABLE account ADD (
  closed_at              TIMESTAMP,
  last_activity_at       TIMESTAMP,
  dormancy_notified_at   TIMESTAMP,
  dormant_at             TIMESTAMP
);

-- Last customer-initiated transaction (最終異動日). Interest credits do not count.
UPDATE account a SET last_activity_at = (
  SELECT MAX(t.created_at) FROM account_transaction t WHERE t.account_no = a.account_no
) WHERE a.last_activity_at IS NULL;
UPDATE account SET last_activity_at = opened_at WHERE last_activity_at IS NULL;

ALTER TABLE account DROP CONSTRAINT ck_account_status;
ALTER TABLE account ADD CONSTRAINT ck_account_status CHECK (status IN ('ACTIVE', 'FROZEN', 'DORMANT', 'CLOSED'));
CREATE INDEX ix_account_activity ON account (status, last_activity_at);

-- 7-digit account numbers for newly opened accounts
CREATE SEQUENCE account_no_seq START WITH 1000008 MAXVALUE 9999999 NOCACHE;

-- ---- Transactions: interest, withheld tax, payout on closure ----
ALTER TABLE account_transaction DROP CONSTRAINT ck_tx_type;
ALTER TABLE account_transaction ADD CONSTRAINT ck_tx_type
  CHECK (tx_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER_OUT', 'TRANSFER_IN', 'INTEREST', 'TAX', 'CLOSE_PAYOUT'));
-- History search by period
CREATE INDEX ix_tx_account_created ON account_transaction (account_no, created_at);

-- ---- Interest rates (annual %, by account type, effective from a date) ----
CREATE TABLE interest_rate (
  account_type    VARCHAR2(10)  NOT NULL,
  effective_from  DATE          NOT NULL,
  annual_rate     NUMBER(7,5)   NOT NULL,
  CONSTRAINT pk_interest_rate PRIMARY KEY (account_type, effective_from),
  CONSTRAINT ck_interest_rate_type CHECK (account_type IN ('ORDINARY', 'SAVINGS')),
  CONSTRAINT ck_interest_rate_value CHECK (annual_rate >= 0)
);

