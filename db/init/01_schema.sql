-- Bank sample schema (Oracle Database 23ai Free / 19c+)
-- Executed once by gvenzl/oracle-free on first database creation (as SYS).
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER USER BANK QUOTA UNLIMITED ON USERS;
ALTER SESSION SET CURRENT_SCHEMA = BANK;

CREATE TABLE customer (
  customer_id   VARCHAR2(10)       NOT NULL,
  name          VARCHAR2(100 CHAR) NOT NULL,
  created_at    TIMESTAMP          DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_customer PRIMARY KEY (customer_id)
);

CREATE TABLE account (
  account_no    VARCHAR2(7)        NOT NULL,
  customer_id   VARCHAR2(10)       NOT NULL,
  account_type  VARCHAR2(10)       NOT NULL,
  balance       NUMBER(15,0)       DEFAULT 0 NOT NULL,
  status        VARCHAR2(10)       DEFAULT 'ACTIVE' NOT NULL,
  opened_at     TIMESTAMP          DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at    TIMESTAMP          DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_account PRIMARY KEY (account_no),
  CONSTRAINT fk_account_customer FOREIGN KEY (customer_id) REFERENCES customer (customer_id),
  CONSTRAINT ck_account_type CHECK (account_type IN ('ORDINARY', 'SAVINGS')),
  CONSTRAINT ck_account_status CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
  CONSTRAINT ck_account_balance CHECK (balance >= 0)
);

CREATE INDEX ix_account_customer ON account (customer_id);

CREATE TABLE account_transaction (
  tx_id                    NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
  account_no               VARCHAR2(7)        NOT NULL,
  tx_type                  VARCHAR2(12)       NOT NULL,
  amount                   NUMBER(15,0)       NOT NULL,
  balance_after            NUMBER(15,0)       NOT NULL,
  counterparty_account_no  VARCHAR2(7),
  memo                     VARCHAR2(50 CHAR),
  idempotency_key          VARCHAR2(64),
  created_at               TIMESTAMP          DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_account_transaction PRIMARY KEY (tx_id),
  CONSTRAINT fk_tx_account FOREIGN KEY (account_no) REFERENCES account (account_no),
  CONSTRAINT ck_tx_type CHECK (tx_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER_OUT', 'TRANSFER_IN')),
  CONSTRAINT ck_tx_amount CHECK (amount > 0)
);

CREATE INDEX ix_tx_account ON account_transaction (account_no, tx_id);

-- Idempotency keys: a retried / double-submitted request is rejected by the primary key.
CREATE TABLE operation_request (
  idempotency_key  VARCHAR2(64)  NOT NULL,
  operation_type   VARCHAR2(12)  NOT NULL,
  created_at       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT pk_operation_request PRIMARY KEY (idempotency_key)
);

COMMENT ON TABLE customer IS '顧客';
COMMENT ON TABLE account IS '口座（残高は円・整数）';
COMMENT ON TABLE account_transaction IS '入出金・振込明細';
COMMENT ON TABLE operation_request IS '冪等キー（二重送信防止）';
