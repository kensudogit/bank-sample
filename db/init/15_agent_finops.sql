-- ---- 使用量の明細（課金の配賦の元データ）----
-- source：GATEWAY（Kong の全要求。http-log）・LLM（Agent の Claude 呼び出し）
CREATE TABLE usage_event (
  event_id           NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  occurred_at        TIMESTAMP           NOT NULL,
  source             VARCHAR2(10)        NOT NULL,
  api_id             VARCHAR2(60)        NOT NULL,
  subject_type       VARCHAR2(12)        NOT NULL,
  subject_id         VARCHAR2(64)        NOT NULL,
  principal          VARCHAR2(64),
  status             NUMBER(3),
  latency_ms         NUMBER(10),
  request_count      NUMBER(10)          DEFAULT 1 NOT NULL,
  model              VARCHAR2(40),
  input_tokens       NUMBER(12)          DEFAULT 0 NOT NULL,
  output_tokens      NUMBER(12)          DEFAULT 0 NOT NULL,
  cache_read_tokens  NUMBER(12)          DEFAULT 0 NOT NULL,
  cache_write_tokens NUMBER(12)          DEFAULT 0 NOT NULL,
  cost_jpy           NUMBER(16,6)        NOT NULL,
  run_id             VARCHAR2(36),
  request_id         VARCHAR2(64),
  CONSTRAINT pk_usage_event PRIMARY KEY (event_id),
  CONSTRAINT ck_usage_event_source CHECK (source IN ('GATEWAY', 'LLM'))
);
CREATE INDEX ix_usage_event_time ON usage_event (occurred_at);
CREATE INDEX ix_usage_event_subject ON usage_event (subject_type, subject_id, occurred_at);

-- ---- AI Agent の実行（誰が・どの Agent で・何を呼び・いくらかかったか）----
CREATE TABLE agent_run (
  run_id         VARCHAR2(36)        NOT NULL,
  agent_id       VARCHAR2(64)        NOT NULL,
  principal      VARCHAR2(64)        NOT NULL,
  principal_oid  VARCHAR2(36),
  started_at     TIMESTAMP           NOT NULL,
  finished_at    TIMESTAMP,
  status         VARCHAR2(12)        NOT NULL,
  model          VARCHAR2(40),
  steps          NUMBER(5)           DEFAULT 0 NOT NULL,
  tool_calls     VARCHAR2(1000 CHAR),
  denied_calls   NUMBER(5)           DEFAULT 0 NOT NULL,
  input_tokens   NUMBER(12)          DEFAULT 0 NOT NULL,
  output_tokens  NUMBER(12)          DEFAULT 0 NOT NULL,
  cache_read_tokens  NUMBER(12)      DEFAULT 0 NOT NULL,
  cache_write_tokens NUMBER(12)      DEFAULT 0 NOT NULL,
  cost_jpy       NUMBER(16,6)        DEFAULT 0 NOT NULL,
  prompt_sha256  VARCHAR2(64),
  trace_id       VARCHAR2(32),
  summary        VARCHAR2(400 CHAR),
  CONSTRAINT pk_agent_run PRIMARY KEY (run_id),
  CONSTRAINT ck_agent_run_status CHECK (status IN ('COMPLETED', 'FAILED', 'BLOCKED', 'LIMITED'))
);
CREATE INDEX ix_agent_run_started ON agent_run (started_at);

-- ---- インフラ費用（Railway の使用量。日・サービスごと）----
CREATE TABLE infra_cost_daily (
  cost_date     DATE                NOT NULL,
  service_name  VARCHAR2(60)        NOT NULL,
  cpu_vcpu_min  NUMBER(16,6)        DEFAULT 0 NOT NULL,
  memory_gb_min NUMBER(16,6)        DEFAULT 0 NOT NULL,
  egress_gb     NUMBER(16,6)        DEFAULT 0 NOT NULL,
  disk_gb       NUMBER(16,6)        DEFAULT 0 NOT NULL,
  cost_usd      NUMBER(16,6)        NOT NULL,
  cost_jpy      NUMBER(16,6)        NOT NULL,
  fetched_at    TIMESTAMP           NOT NULL,
  CONSTRAINT pk_infra_cost_daily PRIMARY KEY (cost_date, service_name)
);

COMMENT ON TABLE usage_event IS '使用量の明細（Kong の全要求・Agent の LLM 呼び出し）と配賦額';
COMMENT ON TABLE agent_run IS 'AI Agent の実行の追跡（行員・Agent・呼んだ API・トークン・費用）';
COMMENT ON TABLE infra_cost_daily IS 'Railway の日次の使用量と費用';

COMMIT;
