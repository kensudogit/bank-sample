-- Loan management: loan-loss provisions (貸倒引当金), collateral revaluation, loan rescheduling (条件変更)
-- Runs after 08_information.sql on first database creation. For an existing database apply it once:
--   docker compose exec oracle bash -c "sqlplus -s / as sysdba @/container-entrypoint-initdb.d/09_loan_management.sql"
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = BANK;

-- Current provision per loan and whether its terms were eased (貸出条件緩和債権 → 要管理先以下)
ALTER TABLE loan ADD (
  provision_amount      NUMBER(15,0)   DEFAULT 0 NOT NULL,
  provision_rate        NUMBER(7,4),
  provision_updated_at  TIMESTAMP,
  restructured          NUMBER(1)      DEFAULT 0 NOT NULL,
  restructure_count     NUMBER(3)      DEFAULT 0 NOT NULL
);
ALTER TABLE loan ADD CONSTRAINT ck_loan_provision CHECK (provision_amount >= 0);
ALTER TABLE loan ADD CONSTRAINT ck_loan_restructured CHECK (restructured IN (0, 1));

-- Every change of a loan's provision (計上・積増し・取崩し) with the basis it was computed from
CREATE TABLE loan_provision (
  provision_id    NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  loan_id         NUMBER(19)          NOT NULL,
  as_of           DATE                NOT NULL,
  borrower_class  VARCHAR2(10)        NOT NULL,
  outstanding     NUMBER(15,0)        NOT NULL,
  secured         NUMBER(15,0)        NOT NULL,
  provision_rate  NUMBER(7,4)         NOT NULL,
  required        NUMBER(15,0)        NOT NULL,
  previous        NUMBER(15,0)        NOT NULL,
  change_amount   NUMBER(15,0)        NOT NULL,
  reason          VARCHAR2(100 CHAR)  NOT NULL,
  created_by      VARCHAR2(30)        NOT NULL,
  created_at      TIMESTAMP           NOT NULL,
  CONSTRAINT pk_loan_provision PRIMARY KEY (provision_id),
  CONSTRAINT fk_provision_loan FOREIGN KEY (loan_id) REFERENCES loan (loan_id)
);
CREATE INDEX ix_provision_loan ON loan_provision (loan_id, provision_id);

-- Collateral revaluation history (再評価)
ALTER TABLE loan_collateral ADD (revalued_at TIMESTAMP);
CREATE TABLE collateral_revaluation (
  revaluation_id  NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  collateral_id   NUMBER(19)          NOT NULL,
  previous_value  NUMBER(15,0)        NOT NULL,
  new_value       NUMBER(15,0)        NOT NULL,
  reason          VARCHAR2(200 CHAR)  NOT NULL,
  revalued_by     VARCHAR2(30)        NOT NULL,
  revalued_at     TIMESTAMP           NOT NULL,
  CONSTRAINT pk_collateral_revaluation PRIMARY KEY (revaluation_id),
  CONSTRAINT fk_revaluation_collateral FOREIGN KEY (collateral_id) REFERENCES loan_collateral (collateral_id)
);
CREATE INDEX ix_revaluation_collateral ON collateral_revaluation (collateral_id, revaluation_id);

-- Loan rescheduling (条件変更): the remaining balance is re-amortised over a new number of months / at a lower rate
CREATE TABLE loan_restructure (
  restructure_id     NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  loan_id            NUMBER(19)          NOT NULL,
  outstanding        NUMBER(15,0)        NOT NULL,
  arrears_interest   NUMBER(15,0)        NOT NULL,
  old_rate           NUMBER(7,5)         NOT NULL,
  new_rate           NUMBER(7,5)         NOT NULL,
  old_remaining      NUMBER(4)           NOT NULL,
  new_remaining      NUMBER(4)           NOT NULL,
  old_payment        NUMBER(15,0),
  new_payment        NUMBER(15,0)        NOT NULL,
  old_maturity       DATE,
  new_maturity       DATE                NOT NULL,
  days_past_due      NUMBER(5)           NOT NULL,
  reason             VARCHAR2(200 CHAR)  NOT NULL,
  approved_by        VARCHAR2(30)        NOT NULL,
  created_at         TIMESTAMP           NOT NULL,
  CONSTRAINT pk_loan_restructure PRIMARY KEY (restructure_id),
  CONSTRAINT fk_restructure_loan FOREIGN KEY (loan_id) REFERENCES loan (loan_id)
);
CREATE INDEX ix_restructure_loan ON loan_restructure (loan_id, restructure_id);

COMMENT ON TABLE loan_provision IS '貸倒引当金の計上履歴（債務者区分・保全額・引当率）';
COMMENT ON TABLE collateral_revaluation IS '担保の再評価履歴';
COMMENT ON TABLE loan_restructure IS '融資の条件変更（貸出条件緩和）の履歴';

COMMIT;
