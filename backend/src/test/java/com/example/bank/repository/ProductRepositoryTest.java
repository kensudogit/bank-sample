package com.example.bank.repository;

import com.example.bank.service.TestDatabase;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.SQLException;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

/** 預金商品の DB アクセス：定期預金の金利と契約、普通預金等の金利、為替相場、汎用の query／execute。 */
class ProductRepositoryTest {
    private static final LocalDate TODAY = LocalDate.of(2026, 11, 20);
    private final ProductRepository repo = new ProductRepository();
    private Connection c;

    @BeforeEach
    void setUp() throws SQLException {
        c = TestDatabase.create().getConnection();
    }

    @AfterEach
    void tearDown() throws SQLException {
        c.close();
    }

    @Test
    void timeDepositRates() throws SQLException {
        assertEquals(0, new BigDecimal("0.40").compareTo(repo.timeDepositRate(c, 12, TODAY)));
        assertNull(repo.timeDepositRate(c, 7, TODAY));
        // 適用開始日（2025-01-01）より前は該当なし
        assertNull(repo.timeDepositRate(c, 12, LocalDate.of(2024, 12, 31)));
        assertEquals(5, repo.timeDepositRates(c, TODAY).size());
    }

    @Test
    void depositRatePicksTheLatestEffectiveRate() throws SQLException {
        assertEquals(0, new BigDecimal("0.20").compareTo(repo.depositRate(c, "ORDINARY", TODAY)));
        assertEquals(0, new BigDecimal("0.001").compareTo(repo.depositRate(c, "ORDINARY", LocalDate.of(2020, 1, 1))));
        assertEquals(0, BigDecimal.ZERO.compareTo(repo.depositRate(c, "NO_SUCH", TODAY)));
    }

    @Test
    void timeDepositLifecycle() throws SQLException {
        String no = new AccountRepository().nextAccountNo(c);
        new AccountRepository().insert(c, no, "CU0001", "TIME", new BigDecimal("1000000"), LocalDateTime.of(2025, 11, 20, 10, 0));
        repo.insertTimeDeposit(c, no, new BigDecimal("1000000"), new BigDecimal("0.40"), 12, LocalDate.of(2025, 11, 20),
                LocalDate.of(2026, 11, 20), "PAYOUT", "1000001");
        Map<String, Object> td = repo.findTimeDeposit(c, no);
        assertNotNull(td);
        assertEquals("1000001", td.get("linkedAccountNo"));
        assertNotNull(repo.lockTimeDeposit(c, no));
        assertTrue(repo.dueTimeDeposits(c, TODAY).contains(no));
        assertFalse(repo.dueTimeDeposits(c, TODAY.minusDays(1)).contains(no));
        repo.rolloverTimeDeposit(c, no, new BigDecimal("1004000"), new BigDecimal("0.40"), TODAY, TODAY.plusYears(1));
        assertFalse(repo.dueTimeDeposits(c, TODAY).contains(no));
        repo.setTimeDepositStatus(c, no, "MATURED");
        assertFalse(repo.dueTimeDeposits(c, TODAY.plusYears(2)).contains(no));
    }

    @Test
    void fxRates() throws SQLException {
        BigDecimal[] usd = repo.fxRate(c, "USD");
        assertEquals(0, new BigDecimal("152.3").compareTo(usd[0]));
        assertEquals(0, BigDecimal.ONE.compareTo(usd[1]));
        assertNull(repo.fxRate(c, "GBP"));
        assertEquals(1, repo.updateFxRate(c, "USD", new BigDecimal("150.0"), new BigDecimal("1.0"), "svc-mule",
                LocalDateTime.of(2026, 11, 20, 9, 0)));
        assertEquals(0, new BigDecimal("150.0").compareTo(repo.fxRate(c, "USD")[0]));
        assertEquals(0, repo.updateFxRate(c, "GBP", BigDecimal.ONE, BigDecimal.ZERO, "x", LocalDateTime.now()));
        assertEquals(2, repo.fxRates(c).size());
    }

    @Test
    void genericHelpersUseCamelCaseKeysAndTypedNulls() throws SQLException {
        ProductRepository.execute(c, "CREATE TABLE helper_probe (probe_id NUMBER GENERATED BY DEFAULT AS IDENTITY, "
                + "some_text VARCHAR2(20), some_date DATE, some_time TIMESTAMP)");
        long id = ProductRepository.insertReturningId(c, "INSERT INTO helper_probe (some_text, some_date, some_time) VALUES (?, ?, ?)",
                "probe_id", "x", TODAY, LocalDateTime.of(2026, 11, 20, 10, 0));
        ProductRepository.execute(c, "INSERT INTO helper_probe (some_text, some_date, some_time) VALUES (?, ?, ?)", null, null, null);
        List<Map<String, Object>> rows = ProductRepository.query(c, "SELECT probe_id, some_text, some_date FROM helper_probe ORDER BY probe_id");
        assertEquals(2, rows.size());
        assertEquals(id, ((Number) rows.get(0).get("probeId")).longValue());
        assertEquals("x", rows.get(0).get("someText"));
        assertNotNull(rows.get(0).get("someDate"));
        assertNull(rows.get(1).get("someText"));
    }
}
